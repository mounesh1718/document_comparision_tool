using System.Diagnostics;
using System.Text;

namespace DocumentChecker.Engine.ExactView;

/// <summary>The PDF a layout engine produced for a document, or why none could be produced.</summary>
public sealed record PdfLayout(byte[]? Pdf, string? Engine, string? Error);

/// <summary>
/// Lays a .docx out as real pages by printing it to PDF with a word processor installed on this computer:
/// Microsoft Word on Windows (exactly what Word prints), otherwise LibreOffice (free, nearly identical).
/// The engine always works on a temporary copy, so the original file is never opened by it.
/// </summary>
public static class PageLayoutConverter
{
    private static readonly TimeSpan Timeout = TimeSpan.FromMinutes(2);

    public const string NoEngineMessage =
        "Exact view needs Microsoft Word (on Windows) or LibreOffice (free, for Windows, macOS and Linux). Install one of them, or use Reading view.";

    public static PdfLayout Convert(string docxPath, string workDirectory)
    {
        Directory.CreateDirectory(workDirectory);
        var name = "layout-" + Guid.NewGuid().ToString("N");
        var copy = Path.Combine(workDirectory, name + ".docx");
        var pdf = Path.Combine(workDirectory, name + ".pdf");
        File.Copy(docxPath, copy, overwrite: true);
        try
        {
            string? wordError = null;
            if (OperatingSystem.IsWindows())
            {
                wordError = RunWord(copy, pdf);
                if (wordError is null && File.Exists(pdf))
                    return new(File.ReadAllBytes(pdf), "Microsoft Word", null);
            }
            if (FindLibreOffice() is { } libreOffice)
            {
                var error = RunLibreOffice(libreOffice, copy, workDirectory);
                if (error is null && File.Exists(pdf))
                    return new(File.ReadAllBytes(pdf), "LibreOffice", null);
                return new(null, null, error ?? "LibreOffice did not produce the pages.");
            }
            return new(null, null, wordError is null ? NoEngineMessage : NoEngineMessage + " (Word: " + wordError + ")");
        }
        finally
        {
            TryDelete(copy);
            TryDelete(pdf);
        }
    }

    /// <summary>Prints the copy to PDF with Word through its automation interface, invisibly and read-only.</summary>
    private static string? RunWord(string docx, string pdf)
    {
        // The paths are generated by this class (temporary folder + GUID), so quoting them is safe.
        var script = $$"""
            $ErrorActionPreference = 'Stop'
            $word = New-Object -ComObject Word.Application
            try {
                $word.Visible = $false
                $word.DisplayAlerts = 0
                $document = $word.Documents.Open('{{docx.Replace("'", "''")}}', $false, $true, $false)
                $document.ExportAsFixedFormat('{{pdf.Replace("'", "''")}}', 17)
                $document.Close(0)
            } finally {
                $word.Quit()
            }
            """;
        var start = new ProcessStartInfo
        {
            FileName = Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.System), @"WindowsPowerShell\v1.0\powershell.exe")
        };
        start.ArgumentList.Add("-NoProfile");
        start.ArgumentList.Add("-NonInteractive");
        start.ArgumentList.Add("-EncodedCommand");
        start.ArgumentList.Add(System.Convert.ToBase64String(Encoding.Unicode.GetBytes(script)));
        return Run(start, "Microsoft Word");
    }

    private static string? RunLibreOffice(string soffice, string docx, string outputDirectory)
    {
        var start = new ProcessStartInfo { FileName = soffice };
        // A private profile lets this run even while the user has LibreOffice open.
        start.ArgumentList.Add("-env:UserInstallation=" + new Uri(Path.Combine(outputDirectory, "libreoffice-profile")).AbsoluteUri);
        start.ArgumentList.Add("--headless");
        start.ArgumentList.Add("--norestore");
        start.ArgumentList.Add("--convert-to");
        start.ArgumentList.Add("pdf");
        start.ArgumentList.Add("--outdir");
        start.ArgumentList.Add(outputDirectory);
        start.ArgumentList.Add(docx);
        return Run(start, "LibreOffice");
    }

    private static string? Run(ProcessStartInfo start, string engine)
    {
        start.UseShellExecute = false;
        start.CreateNoWindow = true;
        start.RedirectStandardOutput = true;
        start.RedirectStandardError = true;
        try
        {
            using var process = Process.Start(start)!;
            var output = process.StandardOutput.ReadToEndAsync();
            var error = process.StandardError.ReadToEndAsync();
            if (!process.WaitForExit(Timeout))
            {
                process.Kill(entireProcessTree: true);
                return $"{engine} did not finish laying out the document within {Timeout.TotalMinutes:0} minutes.";
            }
            return process.ExitCode == 0 ? null : $"{engine} could not lay out the document.";
        }
        catch (Exception exception) when (exception is not OutOfMemoryException)
        {
            return $"{engine} could not be started.";
        }
    }

    /// <summary>The LibreOffice program in its usual install locations, or on the PATH.</summary>
    public static string? FindLibreOffice()
    {
        var candidates = new List<string>();
        if (OperatingSystem.IsMacOS())
            candidates.Add("/Applications/LibreOffice.app/Contents/MacOS/soffice");
        if (OperatingSystem.IsWindows())
            foreach (var folder in new[] { Environment.SpecialFolder.ProgramFiles, Environment.SpecialFolder.ProgramFilesX86 })
                candidates.Add(Path.Combine(Environment.GetFolderPath(folder), "LibreOffice", "program", "soffice.exe"));
        candidates.AddRange(["/usr/bin/soffice", "/usr/bin/libreoffice", "/usr/local/bin/soffice", "/snap/bin/libreoffice"]);
        foreach (var directory in (Environment.GetEnvironmentVariable("PATH") ?? "").Split(Path.PathSeparator, StringSplitOptions.RemoveEmptyEntries))
            candidates.Add(Path.Combine(directory, OperatingSystem.IsWindows() ? "soffice.exe" : "soffice"));
        return candidates.FirstOrDefault(File.Exists);
    }

    private static void TryDelete(string path)
    {
        try { File.Delete(path); }
        catch (IOException) { }
        catch (UnauthorizedAccessException) { }
    }
}
